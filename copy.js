/* 문자열 해시 — 학교마다 다른 변형을 고르되, 다시 생성해도 같은 결과가 나오게 */
function hash(s) { let h = 0; for (const ch of String(s)) h = (h * 31 + ch.charCodeAt(0)) >>> 0; return h; }
const pick = (arr, seed, n = 1) => { const h = hash(seed); const out = []; for (let i = 0; i < n; i++) out.push(arr[(h + i * 7) % arr.length]); return out; };

